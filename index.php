        <details>
          <summary>Why do people look for a second income?<span aria-hidden="true">+</span></summary>
          <p>For the money. Statistics Canada reports that in 2023 about a third of multiple jobholders gave financial necessity as the main reason, and about a third gave extra income. About 1.1 million employed Canadians, 5.6%, held more than one job that year.</p>
        </details>
        <details>
          <summary>What does it cost me?<span aria-hidden="true">+</span></summary>
          <p>Applying costs nothing.</p>
